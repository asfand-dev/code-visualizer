import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import type { ReportData } from '../shared/types.js';

const DATA_MARKER = '<!--CODE_VISUALIZER_DATA-->';

/** Locate the prebuilt single-file UI template (dist/report/index.html). */
export function findTemplate(): string {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const candidates = [
    path.join(here, 'report', 'index.html'),
    path.join(here, '..', 'report', 'index.html'),
    path.join(here, '..', '..', 'dist', 'report', 'index.html'),
    path.join(here, '..', 'dist', 'report', 'index.html'),
  ];
  for (const candidate of candidates) if (fs.existsSync(candidate)) return candidate;
  throw new Error('Report template not found. If you are developing code-visualizer, run "npm run build:ui" first.');
}

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
}

/** Render the report HTML: the UI template with the analysis embedded as gzip+base64 JSON. */
export function renderReportHtml(data: ReportData, templatePath = findTemplate()): string {
  const template = fs.readFileSync(templatePath, 'utf8');
  const json = JSON.stringify(data);
  const encoded = zlib.gzipSync(Buffer.from(json, 'utf8'), { level: 9 }).toString('base64');
  const script = `<script id="cv-data" type="application/octet-stream" data-encoding="gzip-base64">${encoded}</script>`;
  const title = `${escapeHtml(data.project.name)}${data.scope.path ? ` · ${escapeHtml(data.scope.path)}` : ''} · Code Visualizer`;
  let html = template.replace(/<title>[^<]*<\/title>/, `<title>${title}</title>`);
  html = html.includes(DATA_MARKER) ? html.replace(DATA_MARKER, () => script) : html.replace('</body>', () => `${script}</body>`);
  return html;
}

export interface WriteReportResult {
  htmlPath: string;
  jsonPath?: string;
  bytes: number;
}

export function writeReport(data: ReportData, htmlPath: string, options: { json?: boolean; templatePath?: string } = {}): WriteReportResult {
  const dir = path.dirname(htmlPath);
  fs.mkdirSync(dir, { recursive: true });
  // Keep generated reports out of version control without touching the user's .gitignore.
  if (path.basename(dir) === '.code-visualizer') {
    const gi = path.join(dir, '.gitignore');
    if (!fs.existsSync(gi)) fs.writeFileSync(gi, '# Generated by code-visualizer\n*\n');
  }
  const html = renderReportHtml(data, options.templatePath);
  fs.writeFileSync(htmlPath, html);
  let jsonPath: string | undefined;
  if (options.json) {
    jsonPath = htmlPath.replace(/\.html?$/, '') + '.json';
    fs.writeFileSync(jsonPath, JSON.stringify(data, null, 2));
  }
  return { htmlPath, jsonPath, bytes: Buffer.byteLength(html) };
}
